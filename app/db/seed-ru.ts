async function main() {
  const db = getDb();
  let updated = 0;
  for (const [name, ru] of Object.entries(RU)) {
    const dish = await db.query.dishes.findFirst({ where: eq(dishes.name, name) });
    if (!dish) {
      console.log("未找到菜品，跳过:", name);
      continue;
    }
    await db
      .update(dishes)
      .set({ nameRu: ru.nameRu, descriptionRu: ru.descriptionRu })
      .where(eq(dishes.id, dish.id));
    updated++;
  }
  console.log(`俄语翻译回填完成：${updated} 道菜品`);
  process.exit(0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
